/**
 * OpticareView — clinical-style refraction estimate
 * --------------------------------------------------------------------------
 * Visual style mirrors a paper prescription card. Critical differences vs a
 * real Rx:
 *   - Title is "Refraction Estimate", not "Prescription"
 *   - Prominent "SCREENING ONLY · NOT A PRESCRIPTION" banner
 *   - No clinic name, no doctor signature
 *   - Fields we don't measure (CYL, AXIS, ADD, PRISM, PD, IOP) show "—"
 *   - Disclaimer footer
 *
 * This view is for record-keeping / sharing with a real optometrist who can
 * compare the screening number against their own measurements. It must NOT
 * be presented as something a user could take to an optician for glasses.
 * --------------------------------------------------------------------------
 */

import { Platform, ScrollView, StyleSheet, Text, View } from 'react-native';

const PAGE   = '#FFFFFF';
const INK    = '#0F1B33';   // navy
const RULE   = '#0F1B33';
const MUTED  = '#6B7280';
const SOFT   = '#F1F4FA';   // light navy/grey card bg
const WARN_BG = '#FFF8E1';
const WARN_FG = '#8B5A00';

function snellenString(logMAR) {
  if (!Number.isFinite(logMAR)) return '—';
  const denom = Math.round(20 * Math.pow(10, logMAR));
  return `20/${denom}`;
}

function fmtSphere(d) {
  if (!Number.isFinite(d)) return '—';
  return (d >= 0 ? '+' : '') + d.toFixed(2);
}

export default function OpticareView({
  finalResults,
  vaThreshold,
  qualityReport,
  eye,                  // 'left' | 'right'
  recordId,
  date,
  ppi,
}) {
  const sphValue = finalResults?.appRx;
  const isOD = eye === 'right';   // OD = right eye in optometry
  const isOS = eye === 'left';    // OS = left eye

  // Render a row per eye. The eye we tested gets the value; the other shows "—"
  // (since our app currently does one eye per session).
  const odSph = isOD ? fmtSphere(sphValue) : '—';
  const osSph = isOS ? fmtSphere(sphValue) : '—';
  const odVA  = isOD ? snellenString(vaThreshold) : '—';
  const osVA  = isOS ? snellenString(vaThreshold) : '—';

  const dateLabel = date || new Date().toISOString().slice(0, 10);
  const idTail = recordId ? recordId.slice(-8).toUpperCase() : '—';

  return (
    <ScrollView
      style={{ backgroundColor: PAGE }}
      contentContainerStyle={styles.scrollContent}
    >
      {/* Header — clinic-card style */}
      <View style={styles.headerCenter}>
        <Text style={styles.clinicName}>ALL GOOD VISION Screening</Text>
        <Text style={styles.clinicAddr}>SMARTPHONE-BASED REFRACTION</Text>
      </View>

      <View style={styles.headerRule} />

      {/* Title */}
      <View style={styles.titleRow}>
        <Text style={styles.titleText}>Refraction Estimate.</Text>
        <View style={styles.idBox}>
          <Text style={styles.idLabel}>ID</Text>
          <Text style={styles.idValue}>{idTail}</Text>
        </View>
      </View>

      {/* Warning banner — mandatory */}
      <View style={styles.warnBanner}>
        <Text style={styles.warnTitle}>SCREENING ONLY · NOT A PRESCRIPTION</Text>
        <Text style={styles.warnText}>
          This estimate is generated by a research smartphone tool and is not a
          legally valid optical prescription. Take it to a licensed optometrist
          for confirmation before purchasing eyewear.
        </Text>
      </View>

      {/* Patient/session strip */}
      <View style={styles.stripRow}>
        <View style={styles.stripCell}>
          <Text style={styles.cellLabel}>SUBJECT</Text>
          <Text style={styles.cellValue}>—</Text>
        </View>
        <View style={styles.stripCell}>
          <Text style={styles.cellLabel}>DATE OF TEST</Text>
          <Text style={styles.cellValue}>{dateLabel}</Text>
        </View>
      </View>
      <View style={styles.stripRow}>
        <View style={styles.stripCell}>
          <Text style={styles.cellLabel}>EYE TESTED</Text>
          <Text style={styles.cellValue}>{(eye ?? '—').toUpperCase()}</Text>
        </View>
        <View style={styles.stripCell}>
          <Text style={styles.cellLabel}>METHOD</Text>
          <Text style={styles.cellValue}>FAR-POINT, BLUE-LCA</Text>
        </View>
      </View>

      <View style={styles.sectionHeader}>
        <Text style={styles.sectionLabel}>SPECTACLE EQUIVALENT · DISTANCE</Text>
      </View>

      {/* Rx grid */}
      <View style={styles.rxHeaderRow}>
        <Text style={[styles.rxHeader, { flex: 0.8 }]}>EYE</Text>
        <Text style={[styles.rxHeader, { flex: 1.2 }]}>SPH</Text>
        <Text style={[styles.rxHeader, { flex: 1   }]}>CYL</Text>
        <Text style={[styles.rxHeader, { flex: 1   }]}>AXIS</Text>
        <Text style={[styles.rxHeader, { flex: 1   }]}>ADD</Text>
        <Text style={[styles.rxHeader, { flex: 1   }]}>PRISM</Text>
      </View>

      <View style={styles.rxRow}>
        <Text style={[styles.rxEye,    { flex: 0.8 }]}>OD</Text>
        <Text style={[styles.rxValue,  { flex: 1.2 }]}>{odSph}</Text>
        <Text style={[styles.rxValue,  { flex: 1   }]}>—</Text>
        <Text style={[styles.rxValue,  { flex: 1   }]}>—</Text>
        <Text style={[styles.rxValue,  { flex: 1   }]}>—</Text>
        <Text style={[styles.rxValue,  { flex: 1   }]}>—</Text>
      </View>
      <View style={styles.rxRow}>
        <Text style={[styles.rxEye,    { flex: 0.8 }]}>OS</Text>
        <Text style={[styles.rxValue,  { flex: 1.2 }]}>{osSph}</Text>
        <Text style={[styles.rxValue,  { flex: 1   }]}>—</Text>
        <Text style={[styles.rxValue,  { flex: 1   }]}>—</Text>
        <Text style={[styles.rxValue,  { flex: 1   }]}>—</Text>
        <Text style={[styles.rxValue,  { flex: 1   }]}>—</Text>
      </View>

      {/* Auxiliary measurements card */}
      <View style={styles.softCard}>
        <View style={styles.auxRow}>
          <Text style={styles.auxLabel}>VA OD</Text>  <Text style={styles.auxValue}>{odVA}</Text>
          <Text style={styles.auxLabel}>VA OS</Text>  <Text style={styles.auxValue}>{osVA}</Text>
        </View>
        <View style={styles.auxRow}>
          <Text style={styles.auxLabel}>PD DIST</Text> <Text style={styles.auxValue}>—</Text>
          <Text style={styles.auxLabel}>PD NEAR</Text> <Text style={styles.auxValue}>—</Text>
        </View>
        <View style={styles.auxRow}>
          <Text style={styles.auxLabel}>IOP</Text>  <Text style={styles.auxValue}>—</Text>
          <Text style={styles.auxLabel}>LENS</Text> <Text style={styles.auxValue}>—</Text>
        </View>
        <View style={styles.auxRow}>
          <Text style={styles.auxLabel}>SCREEN</Text>
          <Text style={styles.auxValue}>{ppi ? `${ppi} PPI` : '—'}</Text>
          <Text style={styles.auxLabel}>QUALITY</Text>
          <Text style={styles.auxValue}>{qualityReport?.grade ?? '—'} {qualityReport?.score != null ? `(${qualityReport.score})` : ''}</Text>
        </View>
      </View>

      {/* Notes */}
      <Text style={styles.notesText}>
        Spherical equivalent only — cylinder/astigmatism is not measured by this
        screening tool. Add notation refers to near-vision lens addition; not
        evaluated.
      </Text>

      {/* Footer */}
      <View style={styles.footerRule} />
      <View style={styles.footerRow}>
        <View>
          <Text style={styles.footerLabel}>RECORD ID</Text>
          <Text style={styles.footerVal}>{recordId ?? '—'}</Text>
        </View>
        <View>
          <Text style={styles.footerLabel}>STATUS</Text>
          <Text style={[styles.footerVal, { color: WARN_FG }]}>UNVERIFIED</Text>
        </View>
      </View>
    </ScrollView>
  );
}

